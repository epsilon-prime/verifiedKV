"""The FINAL grid (test rows). Writes sweeps only; submitting is a separate, explicit decision.

    python make_grid.py              # writes sweeps/<model>_<len>_r<x>[_fastkvzip|_seeds].yaml

Design (SETUP.md sections 4 and 8; user decisions 2026-10-13):
- models: Qwen3-4B-Instruct-2507, Ministral-3-8B-Instruct-2512 (BF16), Qwen3.5-9B;
- data: RULER-32k and RULER-128k (13 tasks x 50 test rows each; 128k raised from 20 by the user 2026-10-14),
  LOFT-32k / 128k (5 tasks, every test
  question of the task's one context);
- ratios 8x / 16x / 32x (0.875 / 0.9375 / 0.96875);
- arms: no_press (once per model and length), KVzip (`kvzip_c`), Fast KVzip (`fastkvzip`: 2% window, our gates
  for Ministral and Qwen3.5), Bernoulli (`bernoulli_kvzip_c`), needle fetch charged (`needle_final_c`) and
  uncharged (`needle_uncharged_c`: same draw as Bernoulli, sketch + reserve on top), fast needle fetch
  (`fast_needle_final`: needle_final_c on Fast KVzip's gate scores, no window; added by the user 2026-10-14, in the
  `_fastkvzip` sweeps with the other gate arm, LOFT seeds at 16x like needle_final_c);
- LOFT seeds: Bernoulli and both needle arms are stochastic and LOFT has one context per task, so 2 extra
  draws (`*_s1`, `*_s2`) in `_seeds` sweeps; RULER varies the draw across its rows already.
- Trimmed by the user 2026-10-14 (options A + B, ~464 -> ~310 GPU-h): the LOFT extra seeds run at 16x only (the
  headline ratio), and the uncharged needle arm (an ablation) runs at 16x only.

Test rows: run_check samples `df.sample(n, random_state=42)` (a prefix of the seed-42 permutation); every
readiness / tuning row was taken from beyond that prefix (positions >= 150 at 32k, >= 400 at 128k).
"""

import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
MODELS = {
    "qwen3-4b": "Qwen/Qwen3-4B-Instruct-2507",
    "ministral3-8b": "mistralai/Ministral-3-8B-Instruct-2512-BF16",
    "qwen3.5-9b": "Qwen/Qwen3.5-9B",
}
RATIOS = {"r8": 0.875, "r16": 0.9375, "r32": 0.96875}
ARMS = ["kvzip_c", "fastkvzip", "bernoulli_kvzip_c", "needle_final_c", "needle_uncharged_c"]
SEED_ARMS = [f"{a}_s{s}" for s in (1, 2) for a in ("bernoulli_kvzip_c", "needle_final_c", "needle_uncharged_c",
                                                   "fast_needle_final")]
GATE_ARMS = ["fastkvzip", "fast_needle_final"]  # need the Fast KVzip gates, not the KVzip score cache
RULER = ["niah_single_1", "niah_single_2", "niah_single_3", "niah_multikey_1", "niah_multikey_2",
         "niah_multikey_3", "niah_multiquery", "niah_multivalue", "vt", "cwe", "fwe", "qa_1", "qa_2"]
LOFT = ["nq", "hotpotqa", "musique", "qampari", "quest"]
LENGTHS = {"32k": ("ruler32k", 50), "128k": ("ruler128k", 50)}


def write(name, sweep):
    path = os.path.join(HERE, "sweeps", f"{name}.yaml")
    with open(path, "w") as f:
        f.write("# FINAL GRID (test rows), generated by make_grid.py -- submit only on an explicit go\n")
        yaml.safe_dump(sweep, f, sort_keys=False)
    n = len(sweep["cells"]) * len(sweep["arms"])
    print(f"{name}.yaml  {n} runs")


os.makedirs(os.path.join(HERE, "sweeps"), exist_ok=True)
for short, model in MODELS.items():
    for length, (ruler, n_rows) in LENGTHS.items():
        ruler_cells = [{"dataset": ruler, "task": t} for t in RULER]
        loft_cells = [{"dataset": "loft", "task": f"{t}_{length}"} for t in LOFT]
        for rtag, ratio in RATIOS.items():
            base = {"group": f"final_{short}", "model": model, "ratio": ratio, "max_context_length": 200000}
            arms = (["no_press"] if rtag == "r8" else []) + [a for a in ARMS if a != "fastkvzip"
                                                             and (a != "needle_uncharged_c" or rtag == "r16")]
            # RULER and LOFT in separate sweeps: n_samples applies to RULER only (LOFT keeps every test question)
            write(f"{short}_{length}_{rtag}_ruler", {**base, "arms": arms, "n_samples": n_rows, "cells": ruler_cells})
            write(f"{short}_{length}_{rtag}_loft", {**base, "arms": arms, "loft_split": "test", "cells": loft_cells})
            write(f"{short}_{length}_{rtag}_fastkvzip", {**base, "arms": GATE_ARMS, "n_samples": n_rows,
                                                         "cells": ruler_cells})
            write(f"{short}_{length}_{rtag}_fastkvzip_loft", {**base, "arms": GATE_ARMS, "loft_split": "test",
                                                              "cells": loft_cells})
            if rtag == "r16":
                write(f"{short}_{length}_{rtag}_seeds_loft", {**base, "arms": SEED_ARMS, "loft_split": "test",
                                                              "cells": loft_cells})
