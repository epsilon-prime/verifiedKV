#!/usr/bin/env python3
"""Fetch-statistics table (Section 4.5): how often and how much VerifiedKV fetches, as % of the full KV cache.

(a) Qwen3-4B, RULER-32K, 16x, KVzip scores, delta = 0.1, eps0 in {0.01, 0.05, 0.1, 0.3}, 2-bit and exact sketch, split into
    the question pass and the decode steps. Source: experiments/adherence/{csv,csv_perfect}/rows.csv (8 answers,
    two contexts per task, about one million decisions per setting); extracted with --source into fetch_qwen3.csv.
      decisions   share of (query head, layer, forward) decisions that fetch at least one token (decision-weighted)
      kv-heads    share of (KV head, layer, forward) steps that fetch at least one token (query heads merged)
      k           tokens fetched per fetching decision, as % of the context
      read        KV read from host (fetched K/V + shortlist keys / 2) as % of the cache, over all forwards (question pass
                  and decode steps together); the per-pass split stays in fetch_qwen3.csv
(b) All three models, RULER-32K, 16x, KVzip scores, delta = 0.1: KV read per forward (% of the cache), from Krishna's sweep
    results/eps_delta/eps_delta_cells.csv (120 contexts per model; task mean).

Output: fetch_stats.tex (two tabulars; \\input inside a table* in experiments.tex).

Usage (from the paper root):
  python figures/fetch_stats/make_fetch_table.py --source experiments/adherence \\
      --sweep results/eps_delta/eps_delta_cells.csv   # rebuild both extracts
  python figures/fetch_stats/make_fetch_table.py                                 # table from the extracts
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

DELTA = 0.1
MODELS = [("Qwen3", "Qwen3-4B"), ("Qwen3.5", "Qwen3.5-9B"), ("Ministral-3", "Ministral-3-8B")]


def extract_qwen3(src: Path, out: Path) -> None:
    rows = []
    for sketch, sub in (("2-bit", "csv"), ("exact", "csv_perfect")):
        r = pd.read_csv(src / sub / "rows.csv")
        r = r[(r["method"] == "vkv_final") & (r["delta"] == DELTA)]
        for eps, g in r.groupby("eps0"):
            rec = dict(sketch=sketch, eps0=eps, answers=len(g))
            for p in ("q", "d"):
                w = g[f"{p}_decisions"]
                fetched = g[f"{p}_fetch_rate"] * w
                rec[f"{p}_decisions"] = 100 * fetched.sum() / w.sum()
                rec[f"{p}_kvheads"] = 100 * g[f"{p}_fwd_fetch_rate"].mean()
                rec[f"{p}_k_pct"] = 100 * (g[f"{p}_k_mean_when_fetch"] * fetched).sum() / (fetched * g["ctx"]).sum()
                rec[f"{p}_read"] = g[f"{p}_read_pct"].mean()
            rec["t_read"] = g["t_read_pct"].mean()
            rows.append(rec)
    pd.DataFrame(rows).to_csv(out, index=False)
    print(f"Wrote {out}")


def extract_sweep(cells: Path, out: Path) -> None:
    c = pd.read_csv(cells)
    c = c[(c["context_k"] == 32) & (c["method"] == "vkv_final_kvzip") & (c["delta"] == DELTA)]
    c.groupby(["model", "eps"], as_index=False)["read_pct"].mean().to_csv(out, index=False)
    print(f"Wrote {out}")


def f(x: float) -> str:
    return "100" if round(x, 1) >= 100 else f"{x:.1f}"


def main() -> None:
    here = Path(__file__).resolve().parent
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", type=Path, help="experiments/adherence")
    ap.add_argument("--sweep", type=Path, help="results/eps_delta/eps_delta_cells.csv")
    args = ap.parse_args()
    if args.source:
        extract_qwen3(args.source.expanduser(), here / "fetch_qwen3.csv")
    if args.sweep:
        extract_sweep(args.sweep.expanduser(), here / "fetch_models.csv")
    q = pd.read_csv(here / "fetch_qwen3.csv")
    m = pd.read_csv(here / "fetch_models.csv").pivot(index="eps", columns="model", values="read_pct")

    lines = [
        "% Generated by make_fetch_table.py; do not edit by hand.",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular*}{\\textwidth}{@{\\extracolsep{\\fill}}ll|cc|cc|cc|c@{}}",
        "\\toprule",
        " & & \\multicolumn{2}{c|}{Decisions that fetch (\\%)} & \\multicolumn{2}{c|}{KV-head steps that fetch (\\%)} "
        "& \\multicolumn{2}{c|}{Tokens per fetch (\\% of context)} & KV read (\\% of cache) \\\\",
        "Sketch & $\\varepsilon_0$ & Question & Decode & Question & Decode & Question & Decode & Overall \\\\",
        "\\midrule",
    ]
    for i, sketch in enumerate(("2-bit", "exact")):  # "exact" is shown as "perfect", the name used in the paper
        if i:
            lines.append("\\midrule")
        g = q[q["sketch"] == sketch].sort_values("eps0")
        for j, (_, r) in enumerate(g.iterrows()):
            name = ({"exact": "perfect"}.get(sketch, sketch) if j == 0 else "")
            vals = [r["q_decisions"], r["d_decisions"], r["q_kvheads"], r["d_kvheads"], r["q_k_pct"], r["d_k_pct"],
                    r["t_read"]]
            lines.append(f"{name} & {r['eps0']:g} & " + " & ".join(f(v) for v in vals) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular*}", "", "\\vspace{6pt}", "",
              "\\begin{tabular*}{\\textwidth}{@{\\extracolsep{\\fill}}l|" + "c" * len(m) + "@{}}", "\\toprule",
              "KV read per forward (\\% of cache) & " + " & ".join(f"$\\varepsilon_0={e:g}$" for e in m.index)
              + " \\\\", "\\midrule"]
    for key, name in MODELS:
        lines.append(f"{name} & " + " & ".join(f(v) for v in m[key]) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular*}", ""]
    (here / "fetch_stats.tex").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
